def save_synthetic_artifacts() -> Dict[str, str]:
    """Generate and persist synthetic CSV and JSON datasets to data/synthetic/."""
    SYNTHETIC_DIR.mkdir(parents=True, exist_ok=True)
    meals_df = generate_synthetic_meal_records()
    meals_csv_path = SYNTHETIC_DIR / "synthetic_meal_service_records_12m.csv"
    meals_df.to_csv(meals_csv_path, index=False)

    # Also save a small 30-row sample CSV for upload testing in the UI
    sample_upload_path = SYNTHETIC_DIR / "sample_cafeteria_upload_template.csv"
    meals_df.tail(30).to_csv(sample_upload_path, index=False)

    recipients = generate_synthetic_recipients()
    recipients_path = SYNTHETIC_DIR / "synthetic_recipients.json"
    with open(recipients_path, "w", encoding="utf-8") as f:
        json.dump(recipients, f, indent=2)

    return {
        "meals_csv": str(meals_csv_path),
        "sample_upload_csv": str(sample_upload_path),
        "recipients_json": str(recipients_path),
        "num_meal_records": str(len(meals_df)),
        "num_recipients": str(len(recipients)),
    }


if __name__ == "__main__":
    summary = save_synthetic_artifacts()
    print("Synthetic demo datasets generated successfully:", json.dumps(summary, indent=2))
