def generate_synthetic_meal_records(
    end_date: date = date(2026, 10, 14),
    num_days: int = 365,
    seed: int = 202604,
) -> pd.DataFrame:
    """Generate 12 months of deterministic synthetic hostel-mess meal records."""
    rng = np.random.default_rng(seed)
    start_date = end_date - timedelta(days=num_days - 1)
    rows: List[Dict[str, Any]] = []

    for day_offset in range(num_days):
        current_date = start_date + timedelta(days=day_offset)
        dow = current_date.weekday()
        mm_dd = current_date.strftime("%m-%d")
        month = current_date.month

        # Seasonal temperature curve for Greater Noida / Uttar Pradesh
        seasonal_temp = {
            1: 14.5, 2: 18.0, 3: 25.0, 4: 32.5, 5: 37.5, 6: 38.5,
            7: 33.5, 8: 32.0, 9: 31.0, 10: 27.5, 11: 22.0, 12: 16.0,
        }[month]
        temp_c = round(float(seasonal_temp + rng.normal(0, 2.2)), 1)

        if month in (7, 8) and rng.random() < 0.38:
            weather = "rainy"
        elif month in (5, 6) and temp_c > 38.0:
            weather = "extreme_heat"
        elif month in (12, 1) and temp_c < 14.0:
            weather = "cold_fog"
        else:
            weather = "clear"

        is_holiday = 1 if mm_dd in FIXED_HOLIDAYS else 0
        # Semester break periods (mid-Dec and June)
        in_semester_break = (month == 6) or (month == 12 and current_date.day >= 18)
        if in_semester_break and dow in (5, 6):
            is_holiday = 1

        # Special campus events
        special_event = "none"
        if not is_holiday and not in_semester_break:
            if month in (4, 11) and 10 <= current_date.day <= 20:
                special_event = "exam_week"
            elif mm_dd in ("02-18", "02-19", "09-24", "10-10"):
                special_event = "campus_hackathon_fest"
            elif dow == 2 and rng.random() < 0.08:
                special_event = "sports_meet"

        for meal_type in MEAL_TYPES:
            menus = MENU_CATALOG[meal_type]
            # Deterministic menu rotation with occasional festive menu
            menu_idx = (day_offset + (0 if meal_type == "breakfast" else 1 if meal_type == "lunch" else 2)) % len(menus)
            menu_choice = menus[menu_idx]
            menu_cat = menu_choice["category"]
            menu_items = menu_choice["items"]
            menu_factor = menu_choice["factor"]

            base = BASE_DEMAND[meal_type]
            dow_factor = WEEKDAY_MULTIPLIERS[dow]
            holiday_factor = 0.58 if is_holiday else (0.68 if in_semester_break else 1.0)

            event_factor = 1.0
            if special_event == "exam_week":
                event_factor = 1.11  # More students stay in hostel during exams
            elif special_event == "campus_hackathon_fest":
                event_factor = 1.20
            elif special_event == "sports_meet":
                event_factor = 1.08

            weather_factor = 1.0
            if weather == "rainy":
                weather_factor = 1.06 if meal_type in ("lunch", "dinner") else 0.96
            elif weather == "extreme_heat" and meal_type == "lunch":
                weather_factor = 0.93
            elif weather == "cold_fog" and meal_type == "breakfast":
                weather_factor = 0.91

            expected_true_demand = (
                base * dow_factor * menu_factor * holiday_factor * event_factor * weather_factor
            )
            noise = rng.normal(0, base * 0.045)
            true_demand = max(40, int(round(expected_true_demand + noise)))

            # Cafeteria historical preparation behavior (often over-prepares on Fridays/weekends/holidays)
            historical_plan_multiplier = 1.08
            if is_holiday:
                historical_plan_multiplier = 1.24  # Cafeteria failed to scale down fully on holidays
            elif dow in (4, 5, 6):
                historical_plan_multiplier = 1.15
            elif menu_cat == "healthy_millet_bowl":
                historical_plan_multiplier = 1.14

            prep_noise = int(round(rng.normal(0, 14)))
            meals_prepared = max(50, int(round(true_demand * historical_plan_multiplier)) + prep_noise)

            if true_demand <= meals_prepared:
                meals_served = true_demand
                unmet_demand = 0
                leftover = meals_prepared - meals_served
            else:
                meals_served = meals_prepared
                unmet_demand = true_demand - meals_prepared
                leftover = 0

            # Portion of leftovers that were uncollected/spoiled and discarded historically
            discard_fraction = float(rng.uniform(0.32, 0.68)) if leftover > 0 else 0.0
            food_discarded = int(round(leftover * discard_fraction))

            rows.append(
                {
                    "service_date": current_date.isoformat(),
                    "meal_type": meal_type,
                    "menu_category": menu_cat,
                    "menu_items": menu_items,
                    "day_of_week": dow,
                    "is_holiday": is_holiday,
                    "special_event": special_event,
                    "weather_condition": weather,
                    "temperature_c": temp_c,
                    "meals_prepared": meals_prepared,
                    "meals_served": meals_served,
                    "leftover_portions": leftover,
                    "food_discarded_portions": food_discarded,
                    "unmet_demand_portions": unmet_demand,
                    "is_synthetic": 1,
                }
            )

    df = pd.DataFrame(rows)
    return df


